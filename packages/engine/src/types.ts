/**
 * Core data model. Everything in EngineState must stay plain JSON
 * (no classes, no functions) so it can be saved, diffed and replayed.
 */

export type SpanStyle =
  | 'plain'
  | 'muted'
  | 'subtle'
  | 'accent'
  | 'success'
  | 'warning'
  | 'danger'
  | 'echo'
  | 'heading'
  | 'concept'
  | 'path'
  | 'host'
  | 'command';

export interface Span {
  t: string;
  s?: SpanStyle;
  /** Reference for interactive spans: concept id, path, host id or command line. */
  ref?: string;
}

export type Line = Span[];

export type Proto = 'tcp' | 'udp';

export interface Service {
  port: number;
  proto: Proto;
  name: string;
  product?: string;
  version?: string;
  banner?: string;
  state: 'open' | 'filtered';
  tls?: TlsCert;
  http?: HttpResponse;
}

export interface TlsCert {
  subject: string;
  issuer: string;
  notBefore: string;
  notAfter: string;
  san: string[];
  sha256: string;
}

export interface HttpResponse {
  status: number;
  headers: Record<string, string>;
  body: string;
}

export interface Process {
  pid: number;
  user: string;
  cmd: string;
}

export interface Connection {
  proto: Proto;
  local: string;
  remote: string;
  state: 'LISTEN' | 'ESTABLISHED' | 'SYN_SENT' | 'TIME_WAIT' | 'CLOSE_WAIT';
  pid?: number;
  program?: string;
}

export interface DnsRecord {
  name: string;
  type: 'A' | 'AAAA' | 'CNAME' | 'MX' | 'NS' | 'TXT';
  value: string;
  ttl: number;
}

export interface Domain {
  name: string;
  registrar: string;
  registrant: string;
  created: string;
  expires: string;
  nameservers: string[];
  abuse?: string;
  records: DnsRecord[];
  axfr: boolean;
}

export interface Account {
  user: string;
  /** Fictional secret, `null` means no password login (keys only / disabled). */
  password: string | null;
  home: string;
}

export interface VfsFile {
  kind: 'file';
  content: string;
}

export interface VfsDir {
  kind: 'dir';
  children: Record<string, VfsNode>;
}

export type VfsNode = VfsFile | VfsDir;

export interface Host {
  id: string;
  hostname: string;
  ip: string;
  os: string;
  networks: string[];
  /** Answers ICMP echo requests. */
  icmp: boolean;
  services: Service[];
  accounts: Account[];
  fs: VfsDir;
  processes: Process[];
  connections: Connection[];
  /** Optional for saves made before Act II. */
  documents?: Record<string, DocumentMeta>;
  firewall?: FirewallRule[];
}

export interface DocumentMeta {
  title?: string;
  author: string;
  lastModifiedBy?: string;
  company?: string;
  created: string;
  modified: string;
  software?: string;
}

export interface FirewallRule {
  /** IP or CIDR whose traffic is dropped. */
  source: string;
  note?: string;
}

export interface Network {
  id: string;
  cidr: string;
  label?: string;
}

export interface World {
  hosts: Record<string, Host>;
  networks: Record<string, Network>;
  /** Optional for saves made before DNS existed. */
  domains?: Record<string, Domain>;
}

export interface SessionFrame {
  hostId: string;
  user: string;
  cwd: string;
}

export interface Session extends SessionFrame {
  /** Previous frames when connected through ssh; exit pops back. */
  stack: SessionFrame[];
  history: string[];
}

export interface HostKnowledge {
  /** Host appeared on the player's radar (ping, scan, document…). */
  discovered: boolean;
  /** Ports observed open by a scan. */
  ports: number[];
  /** Service versions identified (nmap -sV). */
  fingerprinted: boolean;
  /** Player obtained a shell on it. */
  accessed: boolean;
}

export interface EngineState {
  world: World;
  session: Session;
  knowledge: Record<string, HostKnowledge>;
  /** Simulated world clock, epoch milliseconds. */
  clock: number;
  /** Noise generated by the player, 0–100. */
  exposure: number;
}
